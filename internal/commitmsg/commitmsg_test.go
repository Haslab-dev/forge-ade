func TestBuildPrompt(t *testing.T) {
	t.Run("small diff embeds stat and diff verbatim", func(t *testing.T) {
		diff := "diff --git a/f.txt b/f.txt\n+added line\n"
		stat := " f.txt | 1 +\n"
		want := "Changes summary:\n" + stat + "\n\nDiff:\n" + diff
		if got := buildPrompt(diff, stat); got != want {
			t.Fatalf("buildPrompt small form:\n got %q\nwant %q", got, want)
		}
	})

	t.Run("boundary at exactly 4000 chars uses the small form", func(t *testing.T) {
		diff := strings.Repeat("q", 4000)
		stat := " f.txt | 4000 +\n"
		got := buildPrompt(diff, stat)
		if !strings.HasPrefix(got, "Changes summary:\n") {
			t.Fatalf("prompt at the 4000 boundary should use the small form, got prefix %q", got[:40])
		}
		if strings.Contains(got, "of changed files") || strings.Contains(got, "Partial diff sample:") {
			t.Fatal("prompt at the 4000 boundary should not use the truncated form")
		}
		if !strings.Contains(got, diff) {
			t.Fatal("small form must embed the diff verbatim")
		}
		if !strings.Contains(got, stat) {
			t.Fatal("small form must embed the diffstat")
		}
	})

	t.Run("large diff switches to diffstat plus truncated sample", func(t *testing.T) {
		// 4001 chars: x*2000 followed by z*2001 so truncation is observable
		// ('z' appears nowhere else in the prompt boilerplate).
		diff := strings.Repeat("x", 2000) + strings.Repeat("z", 2001)
		stat := " f.txt | 4001 +-\n"
		got := buildPrompt(diff, stat)

		if !strings.HasPrefix(got, "Changes summary of changed files:\n") {
			t.Fatalf("large diff should use the token-efficient form, got prefix %q", got[:45])
		}
		if !strings.Contains(got, "Partial diff sample:") {
			t.Fatal("large form missing 'Partial diff sample:' section")
		}
		if !strings.Contains(got, stat) {
			t.Fatal("large form must embed the diffstat")
		}
		if !strings.Contains(got, strings.Repeat("x", 2000)) {
			t.Fatal("sample must contain the first 2000 chars of the diff")
		}
		if strings.Contains(got, "z") {
			t.Fatal("sample must not contain content past the 2000-char cutoff")
		}
		if want := strings.Repeat("x", 2000) + "\n...[staged diff truncated for token efficiency]"; !strings.HasSuffix(got, want) {
			t.Fatalf("sample must end with the truncation marker, got suffix %q", got[len(got)-80:])
		}
	})
}

func TestScrub(t *testing.T) {
	tests := []struct {
		name string
		in   string
		want string
		note string
	}{
		{
			name: "plain message passes through",
			in:   "feat(api): add token refresh",
			want: "feat(api): add token refresh",
		},
		{
			name: "markdown fence stripped",
			in:   "```markdown\nfeat(ui): polish buttons\n```",
			want: "feat(ui): polish buttons",
		},
		{
			name: "git fence stripped",
			in:   "```git\nfix(go): close file after read\n```",
			want: "fix(go): close file after read",
		},
		{
			name: "bare fence stripped",
			in:   "```\nchore: tidy imports\n```",
			want: "chore: tidy imports",
		},
		{
			name: "headers, tables, separators and bold lines dropped",
			in:   "# Commit Summary\n\n| file | change |\n|---|---|\n---\n**Generated by AI**\nfeat: real change\nsecond line\nthird line",
			want: "feat: real change\nsecond line",
		},
		{
			name: "h3 header dropped",
			in:   "### Notes\nfeat: header test",
			want: "feat: header test",
		},
		{
			name: "keeps at most two non-empty lines",
			in:   "feat: a\n\nfeat: b\nfeat: c",
			want: "feat: a\nfeat: b",
			note: "blank lines are skipped, not counted",
		},
		{
			name: "all lines filtered returns fence-stripped input verbatim",
			in:   "```markdown\n# Header\n| a | b |\n```",
			want: "# Header\n| a | b |",
			note: "cleanLines empty -> returns the fence-stripped trimmed input, headers and all",
		},
		{
			name: "inner fence not at position 0 is kept",
			in:   "Here is the commit:\n```\nfeat: x\n```",
			want: "Here is the commit:\n```",
			note: "TrimPrefix only affects position 0, so the inner fence survives and consumes the 2-line budget",
		},
		{
			name: "whitespace-only input collapses to empty",
			in:   "   \n\t\n",
			want: "",
		},
	}
	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {
			got := scrub(tc.in)
			if got != tc.want {
				t.Fatalf("scrub(%q):\n got %q\nwant %q%s", tc.in, got, tc.want, noteSuffix(tc.note))
			}
		})
	}
}

func noteSuffix(note string) string {
	if note == "" {
		return ""
	}
	return " (" + note + ")"
}

// TestCollectDiffIntegration drives collectDiff against a real git repository
// (git CLI is what internal/git shells out to). Generate() itself is not
// called — it would nil-panic on the unset LLM client.
func TestCollectDiffIntegration(t *testing.T) {
	if _, err := exec.LookPath("git"); err != nil {
		t.Skip("git CLI not available")
	}

	repo := t.TempDir()
	runGit := func(args ...string) {
		t.Helper()
		cmd := exec.Command("git", args...)
		cmd.Dir = repo
		if out, err := cmd.CombinedOutput(); err != nil {
			t.Fatalf("git %s: %v\n%s", strings.Join(args, " "), err, out)
		}
	}
	write := func(name, content string) {
		t.Helper()
		if err := os.WriteFile(filepath.Join(repo, name), []byte(content), 0o644); err != nil {
			t.Fatalf("write %s: %v", name, err)
		}
	}

	runGit("init")
	runGit("config", "user.email", "test@example.com")
	runGit("config", "user.name", "Test")
	write("file.txt", "alpha content\n")
	runGit("add", ".")
	runGit("-c", "commit.gpgsign=false", "commit", "-m", "init")

	g := &Generator{Git: git.NewEngine()}
	ctx := context.Background()

	t.Run("staged diff preferred", func(t *testing.T) {
		write("file.txt", "beta content\n")
		runGit("add", "file.txt")
		// Extra unstaged change must NOT appear in the staged diff.
		write("file.txt", "beta content\nunstaged gamma\n")

		diff, stat, err := g.collectDiff(ctx, repo)
		if err != nil {
			t.Fatalf("collectDiff error: %v", err)
		}
		if !strings.Contains(diff, "+beta content") {
			t.Errorf("staged diff missing the staged hunk:\n%s", diff)
		}
		if strings.Contains(diff, "gamma") {
			t.Errorf("collectDiff returned the working-tree diff; want the staged one:\n%s", diff)
		}
		if strings.TrimSpace(stat) == "" {
			t.Error("staged diffstat is empty")
		}
	})

	t.Run("falls back to working-tree diff", func(t *testing.T) {
		runGit("reset") // unstage everything; worktree still has beta+gamma

		diff, stat, err := g.collectDiff(ctx, repo)
		if err != nil {
			t.Fatalf("collectDiff error: %v", err)
		}
		if !strings.Contains(diff, "+beta content") || !strings.Contains(diff, "+unstaged gamma") {
			t.Errorf("working-tree diff missing changes vs HEAD:\n%s", diff)
		}
		if strings.TrimSpace(stat) == "" {
			t.Error("working-tree diffstat is empty")
		}
	})

	t.Run("clean repo errors", func(t *testing.T) {
		runGit("-c", "commit.gpgsign=false", "commit", "-am", "second")

		_, _, err := g.collectDiff(ctx, repo)
		if err == nil {
			t.Fatal("collectDiff on a clean repo should error")
		}
		if !strings.Contains(err.Error(), "no changes found") {
			t.Fatalf("error = %v; want it to mention 'no changes found'", err)
		}
	})
}
