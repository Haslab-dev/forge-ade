package app

// Local copies of the tool-argument helpers the desktop-side tool glue needs.
// The canonical versions live in the RakitKode tools package; these exist only
// so browser_tools.go / computeruse_tools.go can stay in the app package.

func argString(args map[string]any, key string) string {
	if v, ok := args[key].(string); ok {
		return v
	}
	return ""
}

func argInt(args map[string]any, key string, def int) int {
	switch v := args[key].(type) {
	case float64:
		return int(v)
	case int:
		return v
	}
	return def
}

func argBool(args map[string]any, key string, def bool) bool {
	if v, ok := args[key].(bool); ok {
		return v
	}
	return def
}
